#!/usr/bin/env python3
"""HEAD-VS-SAMPLE.md: the Public BI sizes on the first rows of each table
against the seeded random sample, from two sizes.csv files TestSizes wrote.

    datasets/publicbi/head_vs_sample.py HEAD/sizes.csv SAMPLE/sizes.csv > datasets/publicbi/HEAD-VS-SAMPLE.md

See that file for how the two were produced.
"""

import csv
import math
import statistics
import sys

FORMATS = ["colbin", "json-v2", "msgpack", "protobuf"]
LABEL = {"colbin": "colbin", "json-v2": "JSON", "msgpack": "MessagePack", "protobuf": "protobuf"}


def load(path):
    sizes = {}
    with open(path, newline="") as f:
        for row in csv.DictReader(f):
            if row["format"] in FORMATS and row["bytes"]:
                sizes[(row["case"].removeprefix("publicbi/"), row["format"])] = (int(row["bytes"]), int(row["gzip"]))
    return sizes


def change(new, old):
    return (new - old) / old


def pct(x):
    return f"{x * 100:+.1f} %"


def geomean_change(pairs):
    logs = [math.log(new / old) for new, old in pairs if old > 0 and new > 0]
    return math.exp(sum(logs) / len(logs)) - 1


def main(head_path, sample_path):
    head, sample = load(head_path), load(sample_path)
    tables = sorted({case for case, _ in head} & {case for case, _ in sample}, key=str.lower)
    out = []
    p = out.append
    p("# Public BI: the first rows against the seeded sample")
    p("")
    p("Not a result of the paper. It is the evidence for the change of subset rule")
    p("recorded in `datasets/README.md` (\"Subset history\"): until 2026-11-02 each table's")
    p("subset was its first 16 384 rows; since then it is a seeded simple random sample")
    p("of 16 384 rows (bottom-k on splitmix64, seed 20261102).")
    p("")
    p("How it was produced: `TestSizes` over `publicbi/*` twice, with the same build")
    p("(the types regenerated by `typesgen` from the sample), once with `COLBIN_DATA`")
    p("pointing at a directory whose `publicbi/` is `datasets/data/publicbi-head/`, then")
    p("`datasets/publicbi/head_vs_sample.py HEAD/sizes.csv SAMPLE/sizes.csv`.")
    p("")
    p("Caveat: the types' `pb:\"sint\"` tags follow the sample. Four head columns hold")
    p("negatives the sample does not (Eixo, MulheresMil and Uberlandia `DataDeInicio`,")
    p("YaleLanguages `DISCHARGEDATE`), so protobuf's head size for those tables is")
    p("slightly larger than with tags fitted to the head.")
    p("")
    p("Change is sample against head: a positive change means the sample is larger.")
    p("")
    p("## Summary")
    p("")
    p("Geometric mean of the per-table change, over the "
      f"{len(tables)} tables (IUBLibrary and TrainsUK1 are shorter than 16 384 rows, so")
    p("both subsets are the whole table and their change is 0).")
    p("")
    p("| format | raw bytes | gzip |")
    p("|---|---:|---:|")
    for fmt in FORMATS:
        raw = [(sample[(t, fmt)][0], head[(t, fmt)][0]) for t in tables if (t, fmt) in head and (t, fmt) in sample]
        gz = [(sample[(t, fmt)][1], head[(t, fmt)][1]) for t in tables if (t, fmt) in head and (t, fmt) in sample]
        p(f"| {LABEL[fmt]} | {pct(geomean_change(raw))} | {pct(geomean_change(gz))} |")
    p("")
    p("colbin's size as a fraction of JSON's, on each subset (median over tables):")
    p("")
    p("| | head | sample |")
    p("|---|---:|---:|")
    for at, label in ((0, "raw"), (1, "gzip")):
        ratios = []
        for subset in (head, sample):
            values = [subset[(t, "colbin")][at] / subset[(t, "json-v2")][at] for t in tables
                      if (t, "colbin") in subset and (t, "json-v2") in subset]
            ratios.append(statistics.median(values))
        p(f"| {label} | {ratios[0]:.3f} | {ratios[1]:.3f} |")
    for fmt in FORMATS:
        p("")
        p(f"## {LABEL[fmt]}")
        p("")
        p("| table | head B | sample B | change | head gzip B | sample gzip B | change |")
        p("|---|---:|---:|---:|---:|---:|---:|")
        for t in tables:
            if (t, fmt) not in head or (t, fmt) not in sample:
                p(f"| {t} | n/a | n/a | | | | |")
                continue
            (hb, hg), (sb, sg) = head[(t, fmt)], sample[(t, fmt)]
            p(f"| {t} | {hb:,} | {sb:,} | {pct(change(sb, hb))} | {hg:,} | {sg:,} | {pct(change(sg, hg))} |".replace(",", " "))
    print("\n".join(out))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
