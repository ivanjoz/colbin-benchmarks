// tex escapes text for LaTeX.
var texEscaper = strings.NewReplacer(
	`\`, `\textbackslash{}`, `&`, `\&`, `%`, `\%`, `$`, `\$`, `#`, `\#`, `_`, `\_`,
	`{`, `\{`, `}`, `\}`, `~`, `\textasciitilde{}`, `^`, `\textasciicircum{}`)

func tex(text string) string { return texEscaper.Replace(text) }

// latexOut collects the files of tables/.
type latexOut struct {
	dir     string
	numbers []string
	written map[string]bool
	err     error
}

// def records one inline number. Keys are dotted, lower case, and may hold
// anything a \csname can; the value is escaped here.
func (out *latexOut) def(key, value string) {
	out.numbers = append(out.numbers, fmt.Sprintf(`\resultdef{%s}{%s}`, key, tex(value)))
}

func (out *latexOut) file(name, source string, lines []string) {
	out.written[name] = true
	comment := "%"
	if strings.HasSuffix(name, ".dat") {
		comment = "#"
	}
	text := comment + " Generated by cmd/summary from " + source + ". Do not edit: run it again.\n" + strings.Join(lines, "\n") + "\n"
	if err := os.WriteFile(filepath.Join(out.dir, name), []byte(text), 0o644); err != nil && out.err == nil {
		out.err = err
	}
}

// row is one line of a tabular.
func row(cells ...string) string { return strings.Join(cells, " & ") + ` \\` }

// cell is the geometric mean of ratios, with a dagger when zeros were left
// out of it (a 0-byte message has no logarithm; the caption says so).
func cell(ratios []float64) string {
	mean, count, zeros := geomean(ratios)
	switch {
	case count == 0 && zeros == 0:
		return "--"
	case count == 0:
		return `0\rlap{$^\dagger$}`
	case zeros > 0:
		return formatRatio(mean) + `\rlap{$^\dagger$}`
	}
	return formatRatio(mean)
}

// defRatio records a geometric mean and its reciprocal ("3.4 times smaller").
func (out *latexOut) defRatio(key string, ratios []float64) {
	mean, count, _ := geomean(ratios)
	if count == 0 {
		return
	}
	out.def(key, formatRatio(mean))
	out.def(key+".x", strconv.FormatFloat(1/mean, 'f', 1, 64))
}

func readCSV(path string) ([]map[string]string, error) {
	file, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer file.Close()
	records, err := csv.NewReader(file).ReadAll()
	if err != nil || len(records) == 0 {
		return nil, err
	}
	var rows []map[string]string
	for _, record := range records[1:] {
		fields := map[string]string{}
		for index, name := range records[0] {
			if index < len(record) {
				fields[name] = record[index]
			}
		}
		if name, ok := fields["case"]; ok && !reported(name) {
			continue
		}
		rows = append(rows, fields)
	}
	return rows, nil
}

func writeLatex(dir string, sizes []sizeRow) error {
	out := &latexOut{dir: filepath.Join(dir, "tables"), written: map[string]bool{}}
	if err := os.MkdirAll(out.dir, 0o755); err != nil {
		return err
	}
	benches := map[string]*benchmarks{}
	for _, regime := range regimes {
		bench, err := readBench(filepath.Join(dir, "bench-"+regime+".txt"))
		if err == nil {
			benches[regime] = bench
		} else if !os.IsNotExist(err) {
			return err
		}
	}

	provisional := latexMachine(out, dir)
	latexBaselines(out, dir)
	latexCounts(out, sizes, benches)
	for _, regime := range regimes {
		latexSizes(out, sizes, regime)
		if bench := benches[regime]; bench != nil {
			latexTimes(out, bench, regime)
		}
		latexVersus(out, sizes, benches[regime], regime)
		latexFigures(out, sizes, benches[regime], regime)
	}
	latexVersusBy(out, sizes, benches, "datasets", groupOrder, func(name, _ string) string { return groupOf(name) })
	latexVersusBy(out, sizes, benches, "categories", categoryOrder, categoryOf)
	if err := latexCoverage(out, dir); err != nil {
		return err
	}
	if err := latexComposition(out, dir); err != nil {
		return err
	}
	if err := latexAblation(out, dir); err != nil {
		return err
	}
	if second, err := readBench(filepath.Join(dir, "bench-web-2.txt")); err == nil && benches["web"] != nil {
		latexRepeatability(out, benches["web"], second)
	} else if err != nil && !os.IsNotExist(err) {
		return err
	}
	if err := latexProbe(out, dir); err != nil {
		return err
	}
	// A run is provisional until it is the paper's: the main text says so in
	// a banner, so a draft built on a smoke test cannot pass for the result.
	out.def("provisional", strings.Join(provisional, "; "))

	out.file("numbers.tex", "every file of the run", out.numbers)
	stale, _ := filepath.Glob(filepath.Join(out.dir, "*"))
	for _, path := range stale {
		name := filepath.Base(path)
		if !out.written[name] && (strings.HasSuffix(name, ".tex") || strings.HasSuffix(name, ".dat")) {
			os.Remove(path)
		}
	}
	return out.err
}

var (
	versionPattern = regexp.MustCompile(`v\d+\.\d+\.\d+[-+.\w]*`)
	goPattern      = regexp.MustCompile(`go(\d+\.\d+(\.\d+)?)`)
)

// latexMachine copies machine.txt's "key: value" lines into numbers.tex as
// machine.<key>, and returns the reasons this run is not one to publish.
func latexMachine(out *latexOut, dir string) (provisional []string) {
	machine, err := os.ReadFile(filepath.Join(dir, "machine.txt"))
	if err != nil {
		return []string{"no machine.txt"}
	}
	fields := map[string]string{}
	var warnings []string
	head := true
	for line := range strings.SplitSeq(string(machine), "\n") {
		if strings.HasPrefix(line, "== ") {
			head = false
		}
		if strings.HasPrefix(line, "Model name:") {
			fields["cpu"] = strings.TrimSpace(strings.TrimPrefix(line, "Model name:"))
		}
		if strings.HasPrefix(line, "WARNING: ") {
			warnings = append(warnings, strings.TrimPrefix(line, "WARNING: "))
		}
		key, value, ok := strings.Cut(line, ": ")
		if !head || !ok || key == "WARNING" {
			continue
		}
		key = strings.ReplaceAll(strings.ToLower(key), " ", "-")
		if _, seen := fields[key]; !seen {
			fields[key] = value
		}
	}
	if match := goPattern.FindStringSubmatch(fields["go"]); match != nil {
		fields["go-version"] = match[1]
	}
	if version := versionPattern.FindString(fields["colbin"]); version != "" {
		fields["colbin-version"] = version
	}
	if commit := fields["colbin-benchmarks"]; len(commit) >= 40 {
		fields["commit"], fields["commit-short"] = commit[:40], commit[:7]
	}
	keys := make([]string, 0, len(fields))
	for key := range fields {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	for _, key := range keys {
		out.def("machine."+key, fields[key])
	}
	for _, warning := range warnings {
		// On a VM (reproduce.sh --vm) the clock is the host's and cpufreq is
		// often not there to read; the probe measures the clock instead.
		// reproduce.sh records that as a host setting now; runs from before
		// it did wrote these two as warnings.
		if fields["frequency-control"] == "host" && (strings.Contains(warning, "has no cpufreq governor to check") ||
			strings.HasPrefix(warning, "turbo: no intel_pstate/no_turbo or cpufreq/boost to read")) {
			continue
		}
		provisional = append(provisional, warning)
	}
	if strings.Contains(fields["colbin"], "go.work") {
		provisional = append(provisional, "colbin built from a local checkout through go.work, not from the tag go.mod requires")
	}
	if strings.Contains(fields["colbin-benchmarks"], "uncommitted") {
		provisional = append(provisional, "colbin-benchmarks had uncommitted changes")
	}
	if !strings.Contains(fields["driver"]+fields["command"], "reproduce.sh") {
		provisional = append(provisional, "not run by reproduce.sh")
	}
	return provisional
}

// latexBaselines is the implementation behind each format and the version this
// binary was built with, which is go.mod's.
func latexBaselines(out *latexOut, dir string) {
	versions := map[string]string{}
	if info, ok := debug.ReadBuildInfo(); ok {
		for _, module := range info.Deps {
			if module.Replace != nil {
				module = module.Replace
			}
			versions[module.Path] = module.Version
		}
	}
	// A module only generated code came from (vtprotobuf) is not linked into
	// this binary; go.mod, in the directory the summary is run from, has it.
	if module, err := os.ReadFile("go.mod"); err == nil {
		for line := range strings.SplitSeq(string(module), "\n") {
			if fields := strings.Fields(line); len(fields) >= 2 && versions[fields[0]] == "" && versionPattern.MatchString(fields[1]) {
				versions[fields[0]] = fields[1]
			}
		}
	}
	// The colbin and the Go a run measured with are the ones machine.txt
	// names: under a go.work, or summarised on another machine, not this
	// binary's.
	goVersion := strings.TrimPrefix(runtime.Version(), "go")
	if machine, err := os.ReadFile(filepath.Join(dir, "machine.txt")); err == nil {
		for line := range strings.SplitSeq(string(machine), "\n") {
			if value, ok := strings.CutPrefix(line, "colbin: "); ok {
				if version := versionPattern.FindString(value); version != "" {
					versions["github.com/ivanjoz/colbin"] = version
				}
			}
			if value, ok := strings.CutPrefix(line, "go: "); ok {
				if match := goPattern.FindStringSubmatch(value); match != nil {
					goVersion = match[1]
				}
			}
		}
	}
	version := func(module string) string {
		if module == "" {
			return "Go " + goVersion
		}
		if found := versions[module]; found != "" && found != "(devel)" {
			return found
		}
		return "--"
	}
	lines := []string{`\begin{tabular}{lll}`, `\toprule`, row("format", "implementation", "version"), `\midrule`}
	for _, format := range formats.Order {
		if entry, ok := implementation[format]; ok {
			lines = append(lines, row(tex(format), tex(entry[0]), tex(version(entry[1]))))
			out.def("version."+format, version(entry[1]))
		}
	}
	lines = append(lines, `\midrule`)
	for _, entry := range compressorImplementation {
		lines = append(lines, row(tex(entry[0]), tex(entry[1]), tex(version(entry[2]))))
	}
	lines = append(lines, `\bottomrule`, `\end{tabular}`)
	out.file("baselines.tex", "the build's module versions (go.mod) and machine.txt", lines)
}

func latexCounts(out *latexOut, sizes []sizeRow, benches map[string]*benchmarks) {
	total := 0
	variants := map[string]bool{}
	for _, regime := range regimes {
		cases := map[string]bool{}
		byGroup := map[string]map[string]bool{}
		for _, size := range sizes {
			variants[size.Format] = true
			if size.Regime != regime {
				continue
			}
			cases[size.Case] = true
			if byGroup[groupOf(size.Case)] == nil {
				byGroup[groupOf(size.Case)] = map[string]bool{}
			}
			byGroup[groupOf(size.Case)][size.Case] = true
		}
		if bench := benches[regime]; bench != nil && len(cases) == 0 {
			for name := range bench.ns {
				cases[name] = true
			}
		}
		out.def("cases."+regime, strconv.Itoa(len(cases)))
		for _, group := range groupOrder {
			out.def("cases."+regime+"."+group, strconv.Itoa(len(byGroup[group])))
		}
		total += len(cases)
	}
	out.def("cases.total", strconv.Itoa(total))
	out.def("formats.total", strconv.Itoa(len(variants)))
	baselines := 0
	for format := range variants {
		if !strings.HasPrefix(format, formats.Colbin) {
			baselines++
		}
	}
	out.def("formats.baselines", strconv.Itoa(baselines))
}

func latexSizes(out *latexOut, sizes []sizeRow, regime string) {
	ratios := sizeRatios(sizes, func(size sizeRow) bool { return size.Regime == regime })
	if len(ratios) == 0 {
		return
	}
	columns := sizeColumns()
	lines := []string{`\begin{tabular}{lr` + strings.Repeat("r", len(columns)) + `}`, `\toprule`,
		row(append([]string{"format", "cases"}, columns...)...), `\midrule`}
	for _, format := range formats.Order {
		if ratios[format] == nil {
			continue
		}
		if format == formats.Colbin {
			lines = append(lines, `\midrule`)
		}
		cells := []string{tex(format), strconv.Itoa(len(ratios[format]["raw"]))}
		for _, column := range columns {
			cells = append(cells, cell(ratios[format][column]))
			out.defRatio("size."+regime+"."+format+"."+column, ratios[format][column])
		}
		out.def("size."+regime+"."+format+".n", strconv.Itoa(len(ratios[format]["raw"])))
		lines = append(lines, row(cells...))
	}
	lines = append(lines, `\bottomrule`, `\end{tabular}`)
	out.file("sizes-"+regime+".tex", "sizes.csv", lines)

	// By dataset: the message as written and under gzip.
	latexByGroup(out, "sizes-datasets-"+regime+".tex", "sizes.csv", "size."+regime, []string{"raw", "gzip"},
		func(group string) map[string]map[string][]float64 {
			return sizeRatios(sizes, func(size sizeRow) bool { return size.Regime == regime && groupOf(size.Case) == group })
		})
}

var timeOps = []string{"encode", "decode-fresh", "decode-reuse", "access"}

func latexTimes(out *latexOut, bench *benchmarks, regime string) {
	inRegime := func(name string) bool { return bench.regime[name] == regime }
	ratios, cases := timeRatios(bench, formats.JSONv2, "decode-fresh", inRegime)
	if cases == 0 {
		return
	}
	lines := []string{`\begin{tabular}{lr` + strings.Repeat("r", len(timeOps)) + `}`, `\toprule`,
		row(append([]string{"format", "cases"}, timeOps...)...), `\midrule`}
	for _, format := range formats.Order {
		if ratios[format] == nil {
			continue
		}
		if format == formats.Colbin {
			lines = append(lines, `\midrule`)
		}
		cells := []string{tex(format), strconv.Itoa(len(ratios[format]["decode-fresh"]))}
		for _, op := range timeOps {
			cells = append(cells, cell(ratios[format][op]))
			out.defRatio("time."+regime+"."+format+"."+op, ratios[format][op])
		}
		out.def("time."+regime+"."+format+".n", strconv.Itoa(len(ratios[format]["decode-fresh"])))
		lines = append(lines, row(cells...))
	}
	lines = append(lines, `\bottomrule`, `\end{tabular}`)
	out.file("times-"+regime+".tex", "bench-"+regime+".txt", lines)
	out.def("time."+regime+".cases", strconv.Itoa(cases))
	out.def("time."+regime+".access.cases", strconv.Itoa(len(ratios[formats.JSONv2]["access"])))

	latexByGroup(out, "times-datasets-"+regime+".tex", "bench-"+regime+".txt", "time."+regime, []string{"encode", "decode-fresh"},
		func(group string) map[string]map[string][]float64 {
			ratios, _ := timeRatios(bench, formats.JSONv2, "decode-fresh", func(name string) bool { return inRegime(name) && groupOf(name) == group })
			return ratios
		})
}

// latexByGroup writes a table of formats against datasets, a pair of columns
// per dataset, and records each cell as <prefix>.<group>.<format>.<column>.
func latexByGroup(out *latexOut, name, source, prefix string, columns []string, ratiosOf func(group string) map[string]map[string][]float64) {
	type part struct {
		group  string
		ratios map[string]map[string][]float64
	}
	var parts []part
	for _, group := range groupOrder {
		if ratios := ratiosOf(group); len(ratios) > 0 {
			parts = append(parts, part{group, ratios})
		}
	}
	if len(parts) == 0 {
		return
	}
	short := map[string]string{"decode-fresh": "decode"}
	head, rules, sub := []string{""}, []string{}, []string{"format"}
	for index, part := range parts {
		first := 2 + index*len(columns)
		head = append(head, fmt.Sprintf(`\multicolumn{%d}{c}{%s}`, len(columns), groupLabel[part.group]))
		rules = append(rules, fmt.Sprintf(`\cmidrule(lr){%d-%d}`, first, first+len(columns)-1))
		for _, column := range columns {
			label := column
			if short[column] != "" {
				label = short[column]
			}
			sub = append(sub, label)
		}
	}
	lines := []string{`\begin{tabular}{l` + strings.Repeat("r", len(parts)*len(columns)) + `}`, `\toprule`,
		row(head...), strings.Join(rules, " "), row(sub...), `\midrule`}
	for _, format := range formats.Order {
		cells, any := []string{tex(format)}, false
		for _, part := range parts {
			for _, column := range columns {
				cells = append(cells, cell(part.ratios[format][column]))
				out.defRatio(prefix+"."+part.group+"."+format+"."+column, part.ratios[format][column])
				any = any || len(part.ratios[format][column]) > 0
			}
		}
		if !any {
			continue
		}
		if format == formats.Colbin {
			lines = append(lines, `\midrule`)
		}
		lines = append(lines, row(cells...))
	}
	lines = append(lines, `\bottomrule`, `\end{tabular}`)
	out.file(name, source, lines)
}

// latexVersus is colbin against each other format on the cases both have a
// number for, which the tables against JSON are not: there a format's mean is
// over its own cases. A cell is the geometric mean of colbin's number over the
// other's, and in how many of those cases colbin's is strictly the lower.
func latexVersus(out *latexOut, sizes []sizeRow, bench *benchmarks, regime string) {
	bySize := map[string]map[string]sizeRow{}
	for _, size := range sizes {
		if size.Regime != regime {
			continue
		}
		if bySize[size.Case] == nil {
			bySize[size.Case] = map[string]sizeRow{}
		}
		bySize[size.Case][size.Format] = size
	}
	type metric struct {
		name  string
		pairs func(other string) [][2]float64 // colbin's number, the other's
	}
	sizeMetric := func(column string) metric {
		return metric{column, func(other string) (pairs [][2]float64) {
			for _, byFormat := range bySize {
				mine, ok := byFormat[formats.Colbin]
				theirs, okOther := byFormat[other]
				if !ok || !okOther {
					continue
				}
				if column == "raw" {
					pairs = append(pairs, [2]float64{float64(mine.Bytes), float64(theirs.Bytes)})
				} else if _, has := theirs.Compressed[column]; has {
					pairs = append(pairs, [2]float64{float64(mine.Compressed[column]), float64(theirs.Compressed[column])})
				}
			}
			return pairs
		}}
	}
	metrics := []metric{}
	if len(bySize) > 0 {
		metrics = append(metrics, sizeMetric("raw"), sizeMetric("gzip"))
	}
	if bench != nil {
		for _, op := range []string{"encode", "decode-fresh", "access"} {
			metrics = append(metrics, metric{op, func(other string) (pairs [][2]float64) {
				for name, byFormat := range bench.ns {
					if bench.regime[name] != regime {
						continue
					}
					mine, theirs := byFormat[formats.Colbin][op], byFormat[other][op]
					if mine > 0 && theirs > 0 {
						pairs = append(pairs, [2]float64{mine, theirs})
					}
				}
				return pairs
			}})
		}
	}
	if len(metrics) == 0 {
		return
	}
	head := []string{"colbin against"}
	for _, metric := range metrics {
		head = append(head, metric.name)
	}
	lines := []string{`\begin{tabular}{l` + strings.Repeat("r", len(metrics)) + `}`, `\toprule`, row(head...), `\midrule`}
	for _, other := range formats.Order {
		if other == formats.Colbin {
			continue
		}
		cells, any := []string{tex(other)}, false
		for _, metric := range metrics {
			pairs := metric.pairs(other)
			if len(pairs) == 0 {
				cells = append(cells, "--")
				continue
			}
			any = true
			var ratios []float64
			wins := 0
			for _, pair := range pairs {
				if pair[0] < pair[1] {
					wins++
				}
				if pair[1] > 0 {
					ratios = append(ratios, pair[0]/pair[1])
				}
			}
			key := "vs." + regime + "." + other + "." + metric.name
			out.defRatio(key, ratios)
			out.def(key+".wins", strconv.Itoa(wins))
			out.def(key+".n", strconv.Itoa(len(pairs)))
			// No \rlap here: the count follows the mean in the same cell.
			mean := strings.ReplaceAll(cell(ratios), `\rlap{$^\dagger$}`, `$^\dagger$`)
			cells = append(cells, fmt.Sprintf(`%s\ {\scriptsize %d/%d}`, mean, wins, len(pairs)))
		}
		if any {
			lines = append(lines, row(cells...))
		}
	}
	lines = append(lines, `\bottomrule`, `\end{tabular}`)
	out.file("versus-"+regime+".tex", "sizes.csv and bench-"+regime+".txt", lines)
}

// latexVersusBy is latexVersus across regimes, cut another way: by dataset
// (kind "datasets") or by category (kind "categories"). Each case falls in
// one group and weighs one in its group's mean, whatever its regime. Two
// tables, sizes (as written and under gzip) and times (encode and
// decode-fresh), each with a pair of columns per group; a cell is colbin's
// number over the other format's, as a geometric mean over the cases both
// carry, and the cases colbin wins. Keys: vs.<kind>.<group>.<format>.<metric>,
// with .wins and .n. colbin's own variants are left out: they are options of
// colbin, not other formats.
func latexVersusBy(out *latexOut, sizes []sizeRow, benches map[string]*benchmarks, kind string, groups []string, groupFor func(name, regime string) string) {
	type pair struct{ mine, theirs float64 }
	// pairs[group][format][metric]
	pairs := map[string]map[string]map[string][]pair{}
	add := func(group, format, metric string, mine, theirs float64) {
		if pairs[group] == nil {
			pairs[group] = map[string]map[string][]pair{}
		}
		if pairs[group][format] == nil {
			pairs[group][format] = map[string][]pair{}
		}
		pairs[group][format][metric] = append(pairs[group][format][metric], pair{mine, theirs})
	}
	bySize := map[string]map[string]sizeRow{}
	regimeOf := map[string]string{}
	for _, size := range sizes {
		if bySize[size.Case] == nil {
			bySize[size.Case] = map[string]sizeRow{}
		}
		bySize[size.Case][size.Format] = size
		regimeOf[size.Case] = size.Regime
	}
	for name, byFormat := range bySize {
		mine, ok := byFormat[formats.Colbin]
		if !ok {
			continue
		}
		group := groupFor(name, regimeOf[name])
		for format, theirs := range byFormat {
			if strings.HasPrefix(format, formats.Colbin) {
				continue
			}
			add(group, format, "raw", float64(mine.Bytes), float64(theirs.Bytes))
			if _, has := theirs.Compressed["gzip"]; has {
				add(group, format, "gzip", float64(mine.Compressed["gzip"]), float64(theirs.Compressed["gzip"]))
			}
		}
	}
	for _, regime := range regimes {
		bench := benches[regime]
		if bench == nil {
			continue
		}
		for name, byFormat := range bench.ns {
			group := groupFor(name, bench.regime[name])
			for format, byOp := range byFormat {
				if strings.HasPrefix(format, formats.Colbin) {
					continue
				}
				for _, op := range []string{"encode", "decode-fresh"} {
					if mine, theirs := byFormat[formats.Colbin][op], byOp[op]; mine > 0 && theirs > 0 {
						add(group, format, op, mine, theirs)
					}
				}
			}
		}
	}
	short := map[string]string{"decode-fresh": "decode", "raw": "as written"}
	for _, table := range []struct {
		name, source string
		metrics      []string
	}{
		{"size", "sizes.csv", []string{"raw", "gzip"}},
		{"time", "bench-web.txt and bench-bulk.txt", []string{"encode", "decode-fresh"}},
	} {
		var shown []string
		for _, group := range groups {
			for _, metric := range table.metrics {
				found := false
				for _, byMetric := range pairs[group] {
					found = found || len(byMetric[metric]) > 0
				}
				if found && !slices.Contains(shown, group) {
					shown = append(shown, group)
				}
			}
		}
		if len(shown) == 0 {
			continue
		}
		width := len(table.metrics)
		head, rules, sub := []string{"colbin against"}, []string{}, []string{""}
		for index, group := range shown {
			first := 2 + index*width
			head = append(head, fmt.Sprintf(`\multicolumn{%d}{c}{%s}`, width, groupLabel[group]))
			rules = append(rules, fmt.Sprintf(`\cmidrule(lr){%d-%d}`, first, first+width-1))
			for _, metric := range table.metrics {
				label := metric
				if short[metric] != "" {
					label = short[metric]
				}
				sub = append(sub, label)
			}
		}
		lines := []string{`\begin{tabular}{l` + strings.Repeat("r", len(shown)*width) + `}`, `\toprule`,
			row(head...), strings.Join(rules, " "), row(sub...), `\midrule`}
		for _, format := range formats.Order {
			if strings.HasPrefix(format, formats.Colbin) {
				continue
			}
			cells, any := []string{tex(format)}, false
			for _, group := range shown {
				for _, metric := range table.metrics {
					list := pairs[group][format][metric]
					if len(list) == 0 {
						cells = append(cells, "--")
						continue
					}
					any = true
					var ratios []float64
					wins := 0
					for _, p := range list {
						if p.mine < p.theirs {
							wins++
						}
						if p.theirs > 0 {
							ratios = append(ratios, p.mine/p.theirs)
						}
					}
					key := "vs." + kind + "." + group + "." + format + "." + metric
					out.defRatio(key, ratios)
					out.def(key+".wins", strconv.Itoa(wins))
					out.def(key+".n", strconv.Itoa(len(list)))
					mean := strings.ReplaceAll(cell(ratios), `\rlap{$^\dagger$}`, `$^\dagger$`)
					cells = append(cells, fmt.Sprintf(`%s\ {\scriptsize %d/%d}`, mean, wins, len(list)))
				}
			}
			if any {
				lines = append(lines, row(cells...))
			}
		}
		lines = append(lines, `\bottomrule`, `\end{tabular}`)
		out.file("versus-"+kind+"-"+table.name+".tex", table.source, lines)
	}
	// How many cases each group has, for the captions.
	counts := map[string]map[string]bool{}
	for name := range bySize {
		group := groupFor(name, regimeOf[name])
		if counts[group] == nil {
			counts[group] = map[string]bool{}
		}
		counts[group][name] = true
	}
	for _, group := range groups {
		out.def("cases."+kind+"."+group, strconv.Itoa(len(counts[group])))
	}
}

// latexFigures writes the figures' data. The trade-off figure is one point per
// format: size under gzip against decode time, both against JSON. The
// distribution figures are each format's per-case ratios, sorted, against the
// fraction of its cases at or below each.
func latexFigures(out *latexOut, sizes []sizeRow, bench *benchmarks, regime string) {
	sizeOf := sizeRatios(sizes, func(size sizeRow) bool { return size.Regime == regime })
	var timeOf map[string]map[string][]float64
	if bench != nil {
		timeOf, _ = timeRatios(bench, formats.JSONv2, "decode-fresh", func(name string) bool { return bench.regime[name] == regime })
	}
	if len(sizeOf) > 0 && timeOf != nil {
		lines := []string{"format raw gzip encode decode"}
		for _, format := range formats.Order {
			fields := []string{format}
			complete := true
			for _, ratios := range [][]float64{sizeOf[format]["raw"], sizeOf[format]["gzip"], timeOf[format]["encode"], timeOf[format]["decode-fresh"]} {
				mean, count, _ := geomean(ratios)
				complete = complete && count > 0
				fields = append(fields, strconv.FormatFloat(mean, 'g', 5, 64))
			}
			if complete {
				lines = append(lines, strings.Join(fields, " "))
			}
		}
		out.file("fig-tradeoff-"+regime+".dat", "sizes.csv and bench-"+regime+".txt", lines)
	}
	distribution := func(name, source string, ratios []float64) {
		sorted := slices.Clone(ratios)
		sorted = slices.DeleteFunc(sorted, func(ratio float64) bool { return ratio <= 0 })
		if len(sorted) == 0 {
			return
		}
		slices.Sort(sorted)
		lines := []string{"fraction ratio"}
		for index, ratio := range sorted {
			lines = append(lines, fmt.Sprintf("%.4f %.5g", float64(index+1)/float64(len(sorted)), ratio))
		}
		out.file(name, source, lines)
	}
	for _, format := range formats.Order {
		distribution("fig-dist-"+regime+"-gzip-"+format+".dat", "sizes.csv", sizeOf[format]["gzip"])
		distribution("fig-dist-"+regime+"-raw-"+format+".dat", "sizes.csv", sizeOf[format]["raw"])
		if timeOf != nil {
			distribution("fig-dist-"+regime+"-decode-"+format+".dat", "bench-"+regime+".txt", timeOf[format]["decode-fresh"])
			distribution("fig-dist-"+regime+"-encode-"+format+".dat", "bench-"+regime+".txt", timeOf[format]["encode"])
		}
	}
}

// latexCoverage counts, per format and regime, the cases it round-trips, the
// ones it encodes but does not round-trip, and the ones it cannot carry.
func latexCoverage(out *latexOut, dir string) error {
	rows, err := readCSV(filepath.Join(dir, "sizes.csv"))
	if os.IsNotExist(err) || len(rows) == 0 {
		return nil
	}
	if err != nil {
		return err
	}
	kinds := []string{"ok", "lossy", "n/a"}
	counts := map[string]map[string]map[string]int{} // format → regime → kind
	present := map[string]bool{}
	for _, fields := range rows {
		kind := "n/a"
		switch status := fields["status"]; {
		case status == "ok":
			kind = "ok"
		case strings.HasPrefix(status, "lossy"):
			kind = "lossy"
		}
		format, regime := fields["format"], fields["regime"]
		if counts[format] == nil {
			counts[format] = map[string]map[string]int{}
		}
		if counts[format][regime] == nil {
			counts[format][regime] = map[string]int{}
		}
		counts[format][regime][kind]++
		present[regime] = true
	}
	head, rules, sub := []string{""}, []string{}, []string{"format"}
	shown := []string{}
	for _, regime := range regimes {
		if !present[regime] {
			continue
		}
		first := 2 + len(shown)*len(kinds)
		head = append(head, fmt.Sprintf(`\multicolumn{%d}{c}{%s}`, len(kinds), regime))
		rules = append(rules, fmt.Sprintf(`\cmidrule(lr){%d-%d}`, first, first+len(kinds)-1))
		sub = append(sub, "round-trips", "lossy", "n/a")
		shown = append(shown, regime)
	}
	lines := []string{`\begin{tabular}{l` + strings.Repeat("r", len(shown)*len(kinds)) + `}`, `\toprule`,
		row(head...), strings.Join(rules, " "), row(sub...), `\midrule`}
	for _, format := range formats.Order {
		if counts[format] == nil {
			continue
		}
		cells := []string{tex(format)}
		for _, regime := range shown {
			for _, kind := range kinds {
				count := counts[format][regime][kind]
				cells = append(cells, strconv.Itoa(count))
				out.def("coverage."+regime+"."+format+"."+strings.ReplaceAll(kind, "/", ""), strconv.Itoa(count))
			}
		}
		lines = append(lines, row(cells...))
	}
	lines = append(lines, `\bottomrule`, `\end{tabular}`)
	out.file("coverage.tex", "sizes.csv", lines)
	return nil
}

// latexComposition is cases.csv by dataset and regime: how much of each
// dataset colbin writes as columnar tables, and what its schema section weighs.
func latexComposition(out *latexOut, dir string) error {
	rows, err := readCSV(filepath.Join(dir, "cases.csv"))
	if os.IsNotExist(err) || len(rows) == 0 {
		return nil
	}
	if err != nil {
		return err
	}
	type total struct {
		cases, rows, tableRows, bytes, tableBytes int
		schemaShare, schemaBytes, perValue        []float64
	}
	totals := map[[2]string]*total{}
	number := func(text string) int { value, _ := strconv.Atoi(text); return value }
	for _, fields := range rows {
		key := [2]string{fields["regime"], groupOf(fields["case"])}
		if totals[key] == nil {
			totals[key] = &total{}
		}
		sum := totals[key]
		sum.cases++
		sum.rows += number(fields["rows"])
		sum.tableRows += number(fields["table_rows"])
		sum.bytes += number(fields["colbin_bytes"])
		sum.tableBytes += number(fields["table_bytes"])
		if size := number(fields["colbin_bytes"]); size > 0 {
			sum.schemaShare = append(sum.schemaShare, 100*float64(number(fields["schema_bytes"]))/float64(size))
			if perValue, err := strconv.ParseFloat(fields["colbin_bytes_per_value"], 64); err == nil {
				sum.perValue = append(sum.perValue, perValue)
			}
		}
		sum.schemaBytes = append(sum.schemaBytes, float64(number(fields["schema_bytes"])))
	}
	percent := func(part, whole int) string {
		if whole == 0 {
			return "--"
		}
		return strconv.FormatFloat(100*float64(part)/float64(whole), 'f', 1, 64)
	}
	middle := func(values []float64, digits int) string {
		if len(values) == 0 {
			return "--"
		}
		return strconv.FormatFloat(median(values), 'f', digits, 64)
	}
	lines := []string{`\begin{tabular}{llrrrrrrr}`, `\toprule`,
		row("regime", "dataset", "cases", "rows", `\shortstack[r]{rows in\\tables (\%)}`, `\shortstack[r]{bytes in\\tables (\%)}`,
			`\shortstack[r]{schema\\(B)}`, `\shortstack[r]{schema /\\message (\%)}`, `\shortstack[r]{bytes /\\value}`), `\midrule`}
	for _, regime := range regimes {
		for _, group := range groupOrder {
			sum := totals[[2]string{regime, group}]
			if sum == nil {
				continue
			}
			lines = append(lines, row(regime, groupLabel[group], strconv.Itoa(sum.cases), strconv.Itoa(sum.rows),
				percent(sum.tableRows, sum.rows), percent(sum.tableBytes, sum.bytes),
				middle(sum.schemaBytes, 0), middle(sum.schemaShare, 2), middle(sum.perValue, 2)))
			key := "composition." + regime + "." + group
			out.def(key+".rows", strconv.Itoa(sum.rows))
			out.def(key+".table-rows", percent(sum.tableRows, sum.rows))
			out.def(key+".table-bytes", percent(sum.tableBytes, sum.bytes))
			out.def(key+".schema-bytes", middle(sum.schemaBytes, 0))
			out.def(key+".schema-share", middle(sum.schemaShare, 2))
		}
	}
	lines = append(lines, `\bottomrule`, `\end{tabular}`)
	out.file("composition.tex", "cases.csv", lines)
	return nil
}

// latexAblation is ablation.csv (matrix.TestAblation): colbin's bytes under
// each table threshold against the default's, and under each forced column
// codec against the scored choice, as geometric means by dataset and regime.
func latexAblation(out *latexOut, dir string) error {
	rows, err := readCSV(filepath.Join(dir, "ablation.csv"))
	if os.IsNotExist(err) || len(rows) == 0 {
		return nil
	}
	if err != nil {
		return err
	}
	type key struct{ name, knob, setting string }
	values := map[key][2]float64{} // bytes, gzip
	regimeOf := map[string]string{}
	var names []string
	settings := map[string][]string{}
	for _, fields := range rows {
		size, _ := strconv.ParseFloat(fields["bytes"], 64)
		gzip, _ := strconv.ParseFloat(fields["gzip"], 64)
		values[key{fields["case"], fields["knob"], fields["setting"]}] = [2]float64{size, gzip}
		if _, seen := regimeOf[fields["case"]]; !seen {
			regimeOf[fields["case"]] = fields["regime"]
			names = append(names, fields["case"])
		}
		if !slices.Contains(settings[fields["knob"]], fields["setting"]) {
			settings[fields["knob"]] = append(settings[fields["knob"]], fields["setting"])
		}
	}
	for _, knob := range []struct{ name, reference, file string }{
		{"threshold", "8", "ablation-threshold.tex"},
		{"codec", "auto", "ablation-codec.tex"},
	} {
		others := slices.DeleteFunc(slices.Clone(settings[knob.name]), func(setting string) bool { return setting == knob.reference })
		if len(others) == 0 {
			continue
		}
		head := []string{"", "", "", fmt.Sprintf(`\multicolumn{%d}{c}{as written}`, len(others)), fmt.Sprintf(`\multicolumn{%d}{c}{gzip}`, len(others))}
		sub := []string{"regime", "dataset", "cases"}
		sub = append(sub, others...)
		sub = append(sub, others...)
		lines := []string{`\begin{tabular}{llr` + strings.Repeat("r", 2*len(others)) + `}`, `\toprule`, row(head...),
			fmt.Sprintf(`\cmidrule(lr){4-%d} \cmidrule(lr){%d-%d}`, 3+len(others), 4+len(others), 3+2*len(others)), row(sub...), `\midrule`}
		for _, regime := range regimes {
			for _, group := range groupOrder {
				cases := 0
				ratios := map[[2]string][]float64{} // setting, "raw" or "gzip"
				for _, name := range names {
					if regimeOf[name] != regime || groupOf(name) != group {
						continue
					}
					reference, ok := values[key{name, knob.name, knob.reference}]
					if !ok || reference[0] == 0 {
						continue // a 0-byte message is 0 bytes under every setting
					}
					cases++
					for _, setting := range others {
						value, ok := values[key{name, knob.name, setting}]
						if !ok {
							continue
						}
						ratios[[2]string{setting, "raw"}] = append(ratios[[2]string{setting, "raw"}], value[0]/reference[0])
						if reference[1] > 0 {
							ratios[[2]string{setting, "gzip"}] = append(ratios[[2]string{setting, "gzip"}], value[1]/reference[1])
						}
					}
				}
				if cases == 0 {
					continue
				}
				cells := []string{regime, groupLabel[group], strconv.Itoa(cases)}
				for _, column := range []string{"raw", "gzip"} {
					for _, setting := range others {
						cells = append(cells, cell(ratios[[2]string{setting, column}]))
						out.defRatio("ablation."+knob.name+"."+regime+"."+group+"."+setting+"."+column, ratios[[2]string{setting, column}])
					}
				}
				lines = append(lines, row(cells...))
			}
		}
		lines = append(lines, `\bottomrule`, `\end{tabular}`)
		out.file(knob.file, "ablation.csv", lines)
	}
	return nil
}

// latexRepeatability compares the two passes over the web cases: how far the
// medians of the same benchmark moved, and how far the ratios between formats
// did, which is what the paper quotes.
func latexRepeatability(out *latexOut, first, second *benchmarks) {
	var differences, drift []float64
	for name, byFormat := range first.ns {
		for format, byOp := range byFormat {
			for op, ns := range byOp {
				again := second.ns[name][format][op]
				if ns > 0 && again > 0 {
					differences = append(differences, math.Abs(again/ns-1))
					drift = append(drift, again/ns)
				}
			}
		}
	}
	if len(differences) == 0 {
		return
	}
	slices.Sort(differences)
	within := func(bound float64) string {
		count := sort.SearchFloat64s(differences, math.Nextafter(bound, 1))
		return strconv.FormatFloat(100*float64(count)/float64(len(differences)), 'f', 1, 64)
	}
	quantile := func(q float64) string {
		return strconv.FormatFloat(100*differences[min(len(differences)-1, int(q*float64(len(differences))))], 'f', 1, 64)
	}
	out.def("repeat.lines", strconv.Itoa(len(differences)))
	out.def("repeat.within3", within(0.03))
	out.def("repeat.within5", within(0.05))
	out.def("repeat.within10", within(0.10))
	out.def("repeat.median", quantile(0.5))
	out.def("repeat.p90", quantile(0.9))
	out.def("repeat.p99", quantile(0.99))
	out.def("repeat.drift", strconv.FormatFloat(100*(median(drift)-1), 'f', 1, 64))

	// A format's time over colbin's, as a geometric mean over the cases both
	// have, in each pass.
	against := func(bench *benchmarks, format, op string) float64 {
		var ratios []float64
		for _, byFormat := range bench.ns {
			mine, theirs := byFormat[formats.Colbin][op], byFormat[format][op]
			if mine > 0 && theirs > 0 {
				ratios = append(ratios, theirs/mine)
			}
		}
		mean, _, _ := geomean(ratios)
		return mean
	}
	ops := []string{"encode", "decode-fresh"}
	lines := []string{`\begin{tabular}{lrrrrrr}`, `\toprule`,
		row("", `\multicolumn{3}{c}{encode}`, `\multicolumn{3}{c}{decode-fresh}`), `\cmidrule(lr){2-4} \cmidrule(lr){5-7}`,
		row("time over colbin's", "pass 1", "pass 2", `diff.\ (\%)`, "pass 1", "pass 2", `diff.\ (\%)`), `\midrule`}
	worst := 0.0
	for _, format := range formats.Order {
		if format == formats.Colbin || first.ns == nil {
			continue
		}
		cells := []string{tex(format)}
		complete := true
		for _, op := range ops {
			one, two := against(first, format, op), against(second, format, op)
			if math.IsNaN(one) || math.IsNaN(two) {
				complete = false
				break
			}
			difference := 100 * math.Abs(two/one-1)
			worst = max(worst, difference)
			cells = append(cells, formatRatio(one), formatRatio(two), strconv.FormatFloat(difference, 'f', 1, 64))
		}
		if complete {
			lines = append(lines, row(cells...))
		}
	}
	lines = append(lines, `\bottomrule`, `\end{tabular}`)
	out.file("repeatability.tex", "bench-web.txt and bench-web-2.txt", lines)
	out.def("repeat.ratio-worst", strconv.FormatFloat(worst, 'f', 1, 64))
}
