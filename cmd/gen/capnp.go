package main

// Cap'n Proto: a .capnp schema from the Go types, capnpc-go's Go code for it,
// and the glue that builds a message from a Go value and reads one back.
//
// Cap'n Proto has no optional scalar, so a *scalar is two fields: the value
// and a bool that says it is present. Everything else maps as it does for
// FlatBuffers: a struct is a struct, a slice a list, []byte is Data.

import (
	"bytes"
	"fmt"
	"hash/fnv"
	"reflect"
	"unicode"
)

func capnpFieldOK(f fieldInfo) string {
	switch f.shape {
	case shOther:
		return fmt.Sprintf("%s has no Cap'n Proto equivalent", f.typ)
	case shMapScalar:
		return "a map would need a list of key-value structs"
	case shSlicePtrStruct:
		return "a list of structs cannot hold a nil element"
	}
	switch lowerFirst(f.goName) {
	case "message", "segment", "string", "which", "isValid", "toPtr", "encodeAsPtr", "decodeFromPtr", "setNewValue":
		return "the field name collides with a method capnpc-go generates"
	}
	return ""
}

func lowerFirst(s string) string {
	r := []rune(s)
	r[0] = unicode.ToLower(r[0])
	return string(r)
}

// capnpScalar is the schema type of a Go scalar, the Go type capnpc-go gives
// it, and whether Set and At return an error (Text does).
func capnpScalar(t reflect.Type) (schema, goT string, errs bool) {
	switch t.Kind() {
	case reflect.Bool:
		return "Bool", "bool", false
	case reflect.Int8:
		return "Int8", "int8", false
	case reflect.Uint8:
		return "UInt8", "uint8", false
	case reflect.Int16:
		return "Int16", "int16", false
	case reflect.Uint16:
		return "UInt16", "uint16", false
	case reflect.Int32:
		return "Int32", "int32", false
	case reflect.Uint32:
		return "UInt32", "uint32", false
	case reflect.Int, reflect.Int64:
		return "Int64", "int64", false
	case reflect.Uint, reflect.Uint64:
		return "UInt64", "uint64", false
	case reflect.Float32:
		return "Float32", "float32", false
	case reflect.Float64:
		return "Float64", "float64", false
	case reflect.String:
		return "Text", "string", true
	}
	panic("not a scalar: " + t.String())
}

type capnpGen struct {
	m    *model
	ok   support
	root reflect.Type
}

func (g *capnpGen) schema(goImport string) []byte {
	hash := fnv.New64a()
	hash.Write([]byte(goImport))
	var out bytes.Buffer
	fmt.Fprintf(&out, "# Code generated by cmd/gen from the Go types. DO NOT EDIT.\n\n@0x%016x;\n\n", hash.Sum64()|1<<63)
	fmt.Fprintf(&out, "using Go = import \"/go.capnp\";\n$Go.package(\"cp\");\n$Go.import(%q);\n", goImport)
	for _, info := range g.m.structs {
		if g.ok[info.typ] != "" {
			continue
		}
		fmt.Fprintf(&out, "\nstruct %s {\n", info.name)
		ordinal := 0
		field := func(name, typeName string) {
			fmt.Fprintf(&out, "  %s @%d :%s;\n", name, ordinal, typeName)
			ordinal++
		}
		for _, f := range info.fields {
			name := lowerFirst(f.goName)
			switch f.shape {
			case shScalar:
				typeName, _, _ := capnpScalar(f.typ)
				field(name, typeName)
			case shBytes:
				field(name, "Data")
			case shPtrScalar:
				typeName, _, _ := capnpScalar(f.typ.Elem())
				field(name, typeName)
				field(name+"Set", "Bool")
			case shSliceScalar:
				elem, _, _ := capnpScalar(f.typ.Elem())
				field(name, "List("+elem+")")
			case shStruct, shPtrStruct:
				field(name, structOf(f).Name())
			case shSliceStruct:
				field(name, "List("+structOf(f).Name()+")")
			}
		}
		fmt.Fprintf(&out, "}\n")
	}
	return out.Bytes()
}

func (g *capnpGen) code(w *writer) {
	for _, info := range g.m.structs {
		if g.ok[info.typ] != "" {
			continue
		}
		g.build(w, info)
		g.read(w, info)
	}
}

// setScalar is the statement that stores x, a Go value of scalar type t, with
// setter.
func setScalar(w *writer, setter string, t reflect.Type, x string) {
	_, goT, errs := capnpScalar(t)
	if errs {
		w.p("if err := %s(string(%s)); err != nil { return err }", setter, x)
	} else {
		w.p("%s(%s(%s))", setter, goT, x)
	}
}

func (g *capnpGen) build(w *writer, info *structInfo) {
	w.p("func buildCP%s(s cp.%s, v *%s) error {", info.name, info.name, g.m.goType(info.typ))
	for _, f := range info.fields {
		set := "s.Set" + f.goName
		dst := "v." + f.goName
		switch f.shape {
		case shScalar:
			setScalar(w, set, f.typ, dst)
		case shBytes:
			w.p("if len(%s) > 0 { if err := %s(%s); err != nil { return err } }", dst, set, dst)
		case shPtrScalar:
			w.p("if %s != nil {", dst)
			setScalar(w, set, f.typ.Elem(), "*"+dst)
			w.p("s.Set%sSet(true)", f.goName)
			w.p("}")
		case shSliceScalar:
			elem := f.typ.Elem()
			w.p("if n := len(%s); n > 0 {", dst)
			w.p("l, err := s.New%s(int32(n))", f.goName)
			w.p("if err != nil { return err }")
			w.p("for i, x := range %s {", dst)
			if _, goT, errs := capnpScalar(elem); errs {
				w.p("if err := l.Set(i, string(x)); err != nil { return err }")
			} else {
				w.p("l.Set(i, %s(x))", goT)
			}
			w.p("}")
			w.p("}")
		case shStruct:
			w.p("{ c, err := s.New%s()", f.goName)
			w.p("if err != nil { return err }")
			w.p("if err := buildCP%s(c, &%s); err != nil { return err } }", structOf(f).Name(), dst)
		case shPtrStruct:
			w.p("if %s != nil { c, err := s.New%s()", dst, f.goName)
			w.p("if err != nil { return err }")
			w.p("if err := buildCP%s(c, %s); err != nil { return err } }", structOf(f).Name(), dst)
		case shSliceStruct:
			w.p("if n := len(%s); n > 0 {", dst)
			w.p("l, err := s.New%s(int32(n))", f.goName)
			w.p("if err != nil { return err }")
			w.p("for i := range %s { if err := buildCP%s(l.At(i), &%s[i]); err != nil { return err } }", dst, structOf(f).Name(), dst)
			w.p("}")
		}
	}
	w.p("return nil")
	w.p("}\n")
}

func (g *capnpGen) read(w *writer, info *structInfo) {
	w.p("func readCP%s(s cp.%s, v *%s) error {", info.name, info.name, g.m.goType(info.typ))
	for _, f := range info.fields {
		get := "s." + f.goName
		dst := "v." + f.goName
		switch f.shape {
		case shScalar:
			if _, _, errs := capnpScalar(f.typ); errs {
				w.p("{ x, err := %s(); if err != nil { return err }; %s = %s(x) }", get, dst, g.m.goType(f.typ))
			} else {
				w.p("%s = %s(%s())", dst, g.m.goType(f.typ), get)
			}
		case shBytes:
			w.p("{ x, err := %s(); if err != nil { return err }", get)
			w.p("if len(x) > 0 { %s = append(%s[:0], x...) } else { %s = nil } }", dst, dst, dst)
		case shPtrScalar:
			elem := g.m.goType(f.typ.Elem())
			w.p("if s.%sSet() {", f.goName)
			if _, _, errs := capnpScalar(f.typ.Elem()); errs {
				w.p("t, err := %s(); if err != nil { return err }; x := %s(t); %s = &x", get, elem, dst)
			} else {
				w.p("x := %s(%s()); %s = &x", elem, get, dst)
			}
			w.p("} else { %s = nil }", dst)
		case shSliceScalar:
			w.p("{ l, err := %s(); if err != nil { return err }", get)
			w.p("%s = formats.Resize(%s, l.Len())", dst, dst)
			if _, _, errs := capnpScalar(f.typ.Elem()); errs {
				w.p("for i := range %s { x, err := l.At(i); if err != nil { return err }; %s[i] = %s(x) } }", dst, dst, g.m.goType(f.typ.Elem()))
			} else {
				w.p("for i := range %s { %s[i] = %s(l.At(i)) } }", dst, dst, g.m.goType(f.typ.Elem()))
			}
		case shStruct:
			w.p("{ c, err := %s(); if err != nil { return err }", get)
			w.p("if err := readCP%s(c, &%s); err != nil { return err } }", structOf(f).Name(), dst)
		case shPtrStruct:
			w.p("if s.Has%s() { c, err := %s(); if err != nil { return err }", f.goName, get)
			w.p("if %s == nil { %s = new(%s) }", dst, dst, g.m.goType(structOf(f)))
			w.p("if err := readCP%s(c, %s); err != nil { return err }", structOf(f).Name(), dst)
			w.p("} else { %s = nil }", dst)
		case shSliceStruct:
			w.p("{ l, err := %s(); if err != nil { return err }", get)
			w.p("%s = formats.Resize(%s, l.Len())", dst, dst)
			w.p("for i := range %s { if err := readCP%s(l.At(i), &%s[i]); err != nil { return err } } }", dst, structOf(f).Name(), dst)
		}
	}
	w.p("return nil")
	w.p("}\n")
}

// rootFuncs writes the functions that build a whole message for a root type
// and read one back, as the adapter wants them.
func (g *capnpGen) rootFuncs(w *writer, info *structInfo) {
	goT := g.m.goType(info.typ)
	w.p("func capnpBuild%s(v *%s) (*capnp.Message, error) {", info.name, goT)
	w.p("msg, seg, err := capnp.NewMessage(capnp.SingleSegment(nil))")
	w.p("if err != nil { return nil, err }")
	w.p("root, err := cp.NewRoot%s(seg)", info.name)
	w.p("if err != nil { return nil, err }")
	w.p("return msg, buildCP%s(root, v)", info.name)
	w.p("}\n")
	w.p("func capnpRead%s(msg *capnp.Message, v *%s) error {", info.name, goT)
	w.p("root, err := cp.ReadRoot%s(msg)", info.name)
	w.p("if err != nil { return err }")
	w.p("return readCP%s(root, v)", info.name)
	w.p("}\n")
}
