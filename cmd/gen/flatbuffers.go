package main

// FlatBuffers: a .fbs schema from the Go types, flatc's Go code for it, and
// the glue that builds a buffer from a Go value and reads one back.
//
// Every struct is a table, so every field is optional on the wire and a field
// at its default is not written — FlatBuffers' own size behaviour. A *scalar
// is an optional scalar (`= null`), so absent and zero stay distinct.

import (
	"bytes"
	"fmt"
	"reflect"
)

func fbFieldOK(f fieldInfo) string {
	switch f.shape {
	case shOther:
		return fmt.Sprintf("%s has no FlatBuffers equivalent", f.typ)
	case shMapScalar:
		return "a map would need a key-value table and a sorted vector"
	case shSlicePtrStruct:
		return "a vector of tables cannot hold a nil element"
	}
	switch f.snake {
	case "init", "table":
		return "the field name collides with a method flatc generates"
	}
	return ""
}

// fbScalar is the .fbs type of a Go scalar, the Go type flatc gives it, and
// the Builder method that prepends one to a vector.
func fbScalar(t reflect.Type) (fbs, goT, prepend string) {
	switch t.Kind() {
	case reflect.Bool:
		return "bool", "bool", "PrependBool"
	case reflect.Int8:
		return "byte", "int8", "PrependInt8"
	case reflect.Uint8:
		return "ubyte", "byte", "PrependByte"
	case reflect.Int16:
		return "short", "int16", "PrependInt16"
	case reflect.Uint16:
		return "ushort", "uint16", "PrependUint16"
	case reflect.Int32:
		return "int", "int32", "PrependInt32"
	case reflect.Uint32:
		return "uint", "uint32", "PrependUint32"
	case reflect.Int, reflect.Int64:
		return "long", "int64", "PrependInt64"
	case reflect.Uint, reflect.Uint64:
		return "ulong", "uint64", "PrependUint64"
	case reflect.Float32:
		return "float", "float32", "PrependFloat32"
	case reflect.Float64:
		return "double", "float64", "PrependFloat64"
	case reflect.String:
		return "string", "string", ""
	}
	panic("not a scalar: " + t.String())
}

type fbGen struct {
	m    *model
	ok   support
	root reflect.Type // the root_type; flatc wants one
}

func (g *fbGen) schema() []byte {
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by cmd/gen from the Go types. DO NOT EDIT.\n\nnamespace fb;\n")
	for _, info := range g.m.structs {
		if g.ok[info.typ] != "" {
			continue
		}
		fmt.Fprintf(&out, "\ntable %s {\n", info.name)
		for _, f := range info.fields {
			var typeName, suffix string
			switch f.shape {
			case shScalar:
				typeName, _, _ = fbScalar(f.typ)
			case shBytes:
				typeName = "[ubyte]"
			case shPtrScalar:
				typeName, _, _ = fbScalar(f.typ.Elem())
				if typeName != "string" {
					suffix = " = null"
				}
			case shSliceScalar:
				elem, _, _ := fbScalar(f.typ.Elem())
				typeName = "[" + elem + "]"
			case shStruct, shPtrStruct:
				typeName = structOf(f).Name()
			case shSliceStruct:
				typeName = "[" + structOf(f).Name() + "]"
			}
			fmt.Fprintf(&out, "  %s: %s%s;\n", f.snake, typeName, suffix)
		}
		fmt.Fprintf(&out, "}\n")
	}
	if g.root != nil {
		fmt.Fprintf(&out, "\nroot_type %s;\n", g.root.Name())
	}
	return out.Bytes()
}

func (g *fbGen) code(w *writer) {
	for _, info := range g.m.structs {
		if g.ok[info.typ] != "" {
			continue
		}
		g.build(w, info)
		g.read(w, info)
	}
}

func (g *fbGen) build(w *writer, info *structInfo) {
	w.p("func buildFB%s(b *flatbuffers.Builder, v *%s) flatbuffers.UOffsetT {", info.name, g.m.goType(info.typ))
	// Everything a table points at is written before the table starts.
	for _, f := range info.fields {
		o := "o" + f.goName
		method := info.name + "Start" + upperCamel(f.snake) + "Vector"
		switch f.shape {
		case shScalar, shPtrScalar:
			t := f.typ
			if f.shape == shPtrScalar {
				t = t.Elem()
			}
			if t.Kind() != reflect.String {
				continue
			}
			w.p("var %s flatbuffers.UOffsetT", o)
			if f.shape == shPtrScalar {
				w.p("if v.%s != nil { %s = b.CreateString(string(*v.%s)) }", f.goName, o, f.goName)
			} else {
				w.p("if v.%s != \"\" { %s = b.CreateString(string(v.%s)) }", f.goName, o, f.goName)
			}
		case shBytes:
			w.p("var %s flatbuffers.UOffsetT", o)
			w.p("if len(v.%s) > 0 { %s = b.CreateByteVector(v.%s) }", f.goName, o, f.goName)
		case shSliceScalar:
			_, goT, prepend := fbScalar(f.typ.Elem())
			w.p("var %s flatbuffers.UOffsetT", o)
			w.p("if n := len(v.%s); n > 0 {", f.goName)
			if f.typ.Elem().Kind() == reflect.String {
				w.p("offsets := make([]flatbuffers.UOffsetT, n)")
				w.p("for i, x := range v.%s { offsets[i] = b.CreateString(string(x)) }", f.goName)
				w.p("fb.%s(b, n)", method)
				w.p("for i := n - 1; i >= 0; i-- { b.PrependUOffsetT(offsets[i]) }")
			} else {
				w.p("fb.%s(b, n)", method)
				w.p("for i := n - 1; i >= 0; i-- { b.%s(%s(v.%s[i])) }", prepend, goT, f.goName)
			}
			w.p("%s = b.EndVector(n)", o)
			w.p("}")
		case shStruct:
			w.p("%s := buildFB%s(b, &v.%s)", o, structOf(f).Name(), f.goName)
		case shPtrStruct:
			w.p("var %s flatbuffers.UOffsetT", o)
			w.p("if v.%s != nil { %s = buildFB%s(b, v.%s) }", f.goName, o, structOf(f).Name(), f.goName)
		case shSliceStruct:
			w.p("var %s flatbuffers.UOffsetT", o)
			w.p("if n := len(v.%s); n > 0 {", f.goName)
			w.p("offsets := make([]flatbuffers.UOffsetT, n)")
			w.p("for i := range v.%s { offsets[i] = buildFB%s(b, &v.%s[i]) }", f.goName, structOf(f).Name(), f.goName)
			w.p("fb.%s(b, n)", method)
			w.p("for i := n - 1; i >= 0; i-- { b.PrependUOffsetT(offsets[i]) }")
			w.p("%s = b.EndVector(n)", o)
			w.p("}")
		}
	}
	w.p("fb.%sStart(b)", info.name)
	for _, f := range info.fields {
		add := "fb." + info.name + "Add" + upperCamel(f.snake)
		o := "o" + f.goName
		switch f.shape {
		case shScalar:
			if f.typ.Kind() == reflect.String {
				w.p("if %s != 0 { %s(b, %s) }", o, add, o)
			} else {
				_, goT, _ := fbScalar(f.typ)
				w.p("%s(b, %s(v.%s))", add, goT, f.goName)
			}
		case shPtrScalar:
			if f.typ.Elem().Kind() == reflect.String {
				w.p("if %s != 0 { %s(b, %s) }", o, add, o)
			} else {
				_, goT, _ := fbScalar(f.typ.Elem())
				w.p("if v.%s != nil { %s(b, %s(*v.%s)) }", f.goName, add, goT, f.goName)
			}
		case shStruct:
			w.p("%s(b, %s)", add, o)
		default:
			w.p("if %s != 0 { %s(b, %s) }", o, add, o)
		}
	}
	w.p("return fb.%sEnd(b)", info.name)
	w.p("}\n")
}

func (g *fbGen) read(w *writer, info *structInfo) {
	w.p("func readFB%s(t *fb.%s, v *%s) {", info.name, info.name, g.m.goType(info.typ))
	for index, f := range info.fields {
		get := "t." + upperCamel(f.snake)
		dst := "v." + f.goName
		switch f.shape {
		case shScalar:
			if f.typ.Kind() == reflect.String {
				w.p("%s = %s(%s())", dst, g.m.goType(f.typ), get)
			} else {
				w.p("%s = %s(%s())", dst, g.m.goType(f.typ), get)
			}
		case shBytes:
			w.p("if x := %sBytes(); len(x) > 0 { %s = append(%s[:0], x...) } else { %s = nil }", get, dst, dst, dst)
		case shPtrScalar:
			elem := g.m.goType(f.typ.Elem())
			if f.typ.Elem().Kind() == reflect.String {
				// An optional string is a string field that is absent; field n
				// sits at vtable offset 4+2n.
				table := "t.Table()"
				w.p("%s = nil", dst)
				w.p("if tab := %s; tab.Offset(%d) != 0 { x := %s(%s()); %s = &x }", table, 4+2*index, elem, get, dst)
			} else {
				w.p("%s = nil", dst)
				w.p("if p := %s(); p != nil { x := %s(*p); %s = &x }", get, elem, dst)
			}
		case shSliceScalar:
			w.p("%s = formats.Resize(%s, %sLength())", dst, dst, get)
			w.p("for i := range %s { %s[i] = %s(%s(i)) }", dst, dst, g.m.goType(f.typ.Elem()), get)
		case shStruct:
			w.p("{ var c fb.%s", structOf(f).Name())
			w.p("if %s(&c) != nil { readFB%s(&c, &%s) } else { %s = %s{} } }", get, structOf(f).Name(), dst, dst, g.m.goType(structOf(f)))
		case shPtrStruct:
			w.p("{ var c fb.%s", structOf(f).Name())
			w.p("if %s(&c) != nil {", get)
			w.p("if %s == nil { %s = new(%s) }", dst, dst, g.m.goType(structOf(f)))
			w.p("readFB%s(&c, %s)", structOf(f).Name(), dst)
			w.p("} else { %s = nil } }", dst)
		case shSliceStruct:
			w.p("%s = formats.Resize(%s, %sLength())", dst, dst, get)
			w.p("{ var c fb.%s", structOf(f).Name())
			w.p("for i := range %s { %s(&c, i); readFB%s(&c, &%s[i]) } }", dst, get, structOf(f).Name(), dst)
		}
	}
	w.p("}\n")
}
