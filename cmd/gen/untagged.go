package main

// The untagged twin: the dataset's type declarations copied with every struct
// tag removed, so colbin derives each field id from its name and writes eight-
// bit keys (K8) where the tagged type writes four-bit ones (K4). The twin is
// declared field for field like the original, so the two share a memory layout
// and the adapter converts a pointer rather than copying a value.

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
)

func untaggedSource(dir string) ([]byte, error) {
	files, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, err
	}
	fset := token.NewFileSet()
	var decls []ast.Decl
	for _, path := range files {
		if strings.HasSuffix(path, "_test.go") || strings.HasSuffix(path, "_gen.go") {
			continue
		}
		file, err := parser.ParseFile(fset, path, nil, parser.SkipObjectResolution)
		if err != nil {
			return nil, err
		}
		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.TYPE {
				continue
			}
			var problem error
			ast.Inspect(gen, func(n ast.Node) bool {
				switch n := n.(type) {
				case *ast.Field:
					n.Tag, n.Doc, n.Comment = nil, nil, nil
				case *ast.TypeSpec:
					n.Doc, n.Comment = nil, nil
				case *ast.SelectorExpr:
					problem = fmt.Errorf("%s: a type from another package", fset.Position(n.Pos()))
				}
				return true
			})
			if problem != nil {
				return nil, problem
			}
			gen.Doc = nil
			decls = append(decls, gen)
		}
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by cmd/gen. DO NOT EDIT.\n\n")
	out.WriteString("// Package untagged is the dataset's types with their struct tags removed: the\n")
	out.WriteString("// K8 (untagged, name-derived ids) side of the tagged-versus-untagged ablation.\n")
	out.WriteString("package untagged\n\n")
	for _, decl := range decls {
		if err := format.Node(&out, fset, decl); err != nil {
			return nil, err
		}
		out.WriteString("\n\n")
	}
	return format.Source(out.Bytes())
}

func writeUntagged(dir, out string) error {
	source, err := untaggedSource(dir)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(out, 0o755); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(out, "types.go"), source, 0o644)
}
